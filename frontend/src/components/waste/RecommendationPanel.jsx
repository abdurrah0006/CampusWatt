import { useEffect, useRef } from 'react';
import { createPortal } from 'react-dom';
import { Copy, Lightbulb, Sparkles, X } from 'lucide-react';
import { Badge } from '../ui/Badge.jsx';
import { Button } from '../ui/Button.jsx';
import { Icon } from '../ui/Icon.jsx';
import { RecommendationCard } from './RecommendationCard.jsx';
import { useToast } from '../../hooks/useToast.js';
import { copyText } from '../../utils/copyText.js';
import { formatAED } from '../../utils/formatters.js';

// Helpers
function buildCopyAllText(items) {
  const lines = items.map((item, index) => `${index + 1}. ${item.roomName} (${item.roomCode}) - ${item.actionTag} [${item.priority}]\n   ${item.recommendation}`);
  return `CampusWatt - Smart Recommendations\n\n${lines.join('\n\n')}`;
}

export function RecommendationPanel({ open, onClose, result, tariff, focusRoomId }) {
  const toast = useToast();
  const closeButtonRef = useRef(null);

  // Keyboard
  useEffect(() => {
    if (!open) return undefined;
    closeButtonRef.current?.focus();
    const handleKey = (event) => {
      if (event.key === 'Escape') onClose();
    };
    window.addEventListener('keydown', handleKey);
    return () => window.removeEventListener('keydown', handleKey);
  }, [open, onClose]);

  if (!open || !result) return null;

  const isAi = result.source === 'ai';
  const totalAED = result.items.reduce((sum, item) => sum + item.monthlySavingsKwh * tariff, 0);
  const actionCount = result.items.length;

  // Handlers
  const handleCopyAll = async () => {
    const success = await copyText(buildCopyAllText(result.items));
    if (success) toast.success('Copied', `${actionCount} recommendations copied to the clipboard.`);
    else toast.error('Copy failed', 'Your browser blocked clipboard access.');
  };

  // Render
  return createPortal(
    <div className="fixed inset-0 z-50" role="dialog" aria-modal="true" aria-labelledby="recommendations-title">
      <div className="absolute inset-0 bg-overlay backdrop-blur-sm" onClick={onClose} aria-hidden="true" />
      <div className="absolute inset-y-0 right-0 flex w-full max-w-xl animate-slide-in flex-col border-l border-line bg-canvas">
        {/* Header */}
        <header className="border-b border-line bg-surface px-6 py-5">
          <div className="flex items-start justify-between gap-4">
            <div>
              <div className="flex items-center gap-2">
                <span className="flex h-10 w-10 items-center justify-center rounded-xl bg-brand-soft text-brand-primary">
                  <Icon icon={isAi ? Sparkles : Lightbulb} />
                </span>
                <h2 id="recommendations-title" className="text-lg font-semibold text-ink-primary">Smart Recommendations</h2>
              </div>
              <p className="mt-2 text-sm text-ink-secondary">
                {actionCount} action{actionCount === 1 ? '' : 's'} · up to <span className="font-semibold text-brand-primary">{formatAED(totalAED)}/month</span>
              </p>
              <p className="mt-1 text-xs text-ink-muted">
                {isAi ? 'Written by an AI model from the simulated numbers.' : 'Generated by the rule-based engine from simulated usage, schedules and room type.'}
              </p>
            </div>
            <button ref={closeButtonRef} type="button" onClick={onClose} className="icon-button" aria-label="Close recommendations">
              <Icon icon={X} />
            </button>
          </div>
        </header>

        {/* List */}
        <div className="flex-1 space-y-3 overflow-y-auto p-6 scrollbar-thin">
          {result.items.map((item) => (
            <RecommendationCard key={item.roomId} item={item} tariff={tariff} highlighted={item.roomId === focusRoomId} />
          ))}
        </div>

        {/* Footer */}
        <footer className="flex items-center justify-between gap-3 border-t border-line bg-surface px-6 py-4">
          <Badge tone={isAi ? 'info' : 'neutral'}>{isAi ? 'AI-assisted' : 'Rule-based'}</Badge>
          <div className="flex gap-2">
            <Button variant="secondary" icon={Copy} onClick={handleCopyAll}>Copy all</Button>
            <Button onClick={onClose}>Done</Button>
          </div>
        </footer>
      </div>
    </div>,
    document.body,
  );
}
